/**
 * The inline SVGs this view uses. They were repeated verbatim up to four times
 * each — eight lines of path data per occurrence — which is most of why the
 * original file was 1,169 lines long. `currentColor` throughout, so each one
 * inherits the colour of whatever control it sits in.
 */
type IconProps = {
  size?: number;
  className?: string;
  strokeWidth?: number;
};

function Svg({
  size = 14,
  className,
  strokeWidth = 2,
  children,
}: IconProps & { children: React.ReactNode }) {
  return (
    <svg
      className={className}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
    >
      {children}
    </svg>
  );
}

